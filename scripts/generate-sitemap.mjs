// Regenerates public/sitemap.xml from courses/*/course.json — one <url> per course
// page, plus the root. Runs before build (see package.json) so it can never drift
// from what's actually under courses/. Needs real per-route URLs to be worth doing
// at all (see BrowserRouter in App.tsx) — course pages weren't separately crawlable
// under the old HashRouter, so there was nothing to list but the root.
import { readdirSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const coursesRoot = join(repoRoot, 'courses');
const ORIGIN = 'https://nptel.danny.co.in';
const today = new Date().toISOString().slice(0, 10);

const courseIds = existsSync(coursesRoot)
  ? readdirSync(coursesRoot)
      .filter((id) => statSync(join(coursesRoot, id)).isDirectory())
      .sort()
  : [];

const urls = [
  { loc: `${ORIGIN}/`, priority: '1.0', changefreq: 'weekly' },
  ...courseIds.map((id) => ({
    loc: `${ORIGIN}/c/${id}`,
    priority: '0.8',
    changefreq: 'monthly',
  })),
];

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-sitemap.mjs — do not edit by hand, it runs on every build. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    (u) => `  <url>
    <loc>${u.loc}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${u.changefreq}</changefreq>
    <priority>${u.priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`;

writeFileSync(join(repoRoot, 'public', 'sitemap.xml'), xml);
console.log(`sitemap.xml: ${urls.length} url(s) (1 root + ${courseIds.length} course page(s))`);
